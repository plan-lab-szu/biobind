"""Generate the revised supplementary Bosphorus table from separated counts.

Historical make_bosphorus_tables.py continues to reproduce the old combined
metric. Use this generator for the revised working manuscript.
"""
import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
THRESHOLDS = ["FMR<=0.001", "FMR<=0.0001", "FMR<=1e-05", "FMR<=1e-06"]
ATTENDED = [
    ("Eyes occluded", "O_EYE"), ("Mouth occluded", "O_MOUTH"),
    ("Glasses", "O_GLASSES"), ("Hair occluded", "O_HAIR"),
    ("Six emotional expressions", "E_all"), ("Lower-face action units", "LFAU_all"),
    ("Upper-face action units", "UFAU_all"), ("Combined action units", "CAU_all"),
    (r"Yaw up to $30^\circ$", "YR_le30"), ("Slight pitch", "PR_slight"),
    ("Pooled conditions", "ATTENDED_pooled"),
]
OTHER = [(r"Yaw $45^\circ$", "YR_45"), (r"Yaw $90^\circ$", "YR_90"),
         ("Full pitch", "PR_full"), ("Diagonal turn", "CR_all")]


def number(n):
    return f"{n:,}".replace(",", "{,}")


def cell(rate):
    ci = rate["clusterCi95"]
    if ci is None:
        return f"{100 * rate['rate']:.1f}" + r"\,[--]"
    return r"%.1f\,[%.1f, %.1f]" % (100 * rate["rate"], 100 * ci[0], 100 * ci[1])


def render(data):
    tables = data["tables"]

    def row(label, group):
        values = [tables[t]["groups"][group] for t in THRESHOLDS]
        n, failures = values[0]["submitted"], values[0]["detectionFailure"]["k"]
        assert all(v["submitted"] == n and v["detectionFailure"]["k"] == failures for v in values)
        cells = " & ".join(cell(v["matchingMissDetected"]) for v in values)
        return f"{label} & {number(n)} & {failures} & {cells} " + r"\\"

    lines = [
        r"% Generated by experiments/biometric/scripts/make_bosphorus_reanalysis_table.py",
        r"\begin{table*}[t]", r"\centering", r"\begingroup\color{black}",
        r"\caption{Bosphorus matching misses among detected probes (\%, 95\% subject-cluster bootstrap intervals; R-BOSPHORUS-REANALYSIS-20261114). $n$ counts all probes and $D$ counts detection failures; the matching-rate denominator is $n-D$. Headers give LFW per-pair false-match calibration targets. The original protocol grouping is retained; no station acceptance gate was run. Intervals condition on the fixed gallery and thresholds; -- marks an omitted interval for zero observed events. The last row reports false duplicates against the other 97 gallery entries.}",
        r"\label{tab:bosphorus}", r"\footnotesize", r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{3.8cm}rrrrrr@{}}",
        r"\toprule", r"Condition & $n$ & $D$ & $10^{-3}$ & $10^{-4}$ & $10^{-5}$ & $10^{-6}$ \\",
        r"\midrule", r"\multicolumn{7}{@{}l}{\textit{Conditions grouped as plausible for attended capture}} \\",
    ]
    lines += [row(label, group) for label, group in ATTENDED]
    lines += [r"\addlinespace[2pt]", r"\multicolumn{7}{@{}l}{\textit{Larger rotations outside that grouping}} \\"]
    lines += [row(label, group) for label, group in OTHER]
    lines += [r"\addlinespace[2pt]", r"\multicolumn{7}{@{}l}{\textit{Controls}} \\",
              row("Same person, neutral repeat", "N_repeat_control")]
    control = [tables[t]["falseDuplicateControl"] for t in THRESHOLDS]
    lines += [f"False duplicates, 97-person gallery & {control[0]['n']} & 0 & "
              + " & ".join(cell(v) for v in control) + r"\\",
              r"\bottomrule", r"\end{tabular}", r"\endgroup", r"\end{table*}"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=ROOT / "experiments/biometric/results/bosphorus_reanalysis_20261114.json")
    parser.add_argument("--out", type=Path, default=ROOT / "experiments/biometric/tables/bosphorus-full.tex")
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(json.loads(args.results.read_text(encoding="utf-8"))), encoding="utf-8")
    print(args.out)


if __name__ == "__main__":
    main()
